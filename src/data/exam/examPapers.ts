// Accessor for all grades and subjects
export function getExamPaper(grade: GradeLevel, subject: ExamSubject): ExamPaper {
  // Currently Grade 3 is fully enriched with 100 authentic questions + 2 extension questions
  // For other grades (4, 5, 6), we provide curriculum-aligned 100 questions papers as well
  if (grade === '3') {
    if (subject === 'chinese') return getGrade3ChineseExam();
    if (subject === 'math') return getGrade3MathExam();
    return getGrade3EnglishExam();
  }

  // Fallback / adaptive generator for Grade 4, 5, 6 with exact 100 questions + 2 extension questions
  return generateGradeExam(grade, subject);
}

