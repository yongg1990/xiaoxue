// Helper to create true/false judge questions
function makeJudge(
  id: string,
  number: number,
  sectionTitle: string,
  stem: string,
  isTrue: boolean,
  explanation: string
): ExamQuestion {
  return {
    id,
    number,
    type: 'judge',
    sectionTitle,
    stem,
    options: ['正确 (√)', '错误 (×)'],
    correctAnswer: isTrue ? 0 : 1,
    explanation,
    points: 1,
  };
}

// Helper to create multiple-choice questions
function makeChoice(
  id: string,
  number: number,
  sectionTitle: string,
  stem: string,
  options: string[],
  correctIndex: number,
  explanation: string,
  readingPassage?: string,
  type: 'choice' | 'calc' | 'reading' | 'application' = 'choice'
): ExamQuestion {
  return {
    id,
    number,
    type,
    sectionTitle,
    stem,
    readingPassage,
    options,
    correctAnswer: correctIndex,
    explanation,
    points: 1,
  };
}

// Helper to create extension challenge questions
function makeExtension(
  id: string,
  number: number,
  stem: string,
  options: string[],
  correctIndex: number,
  explanation: string
): ExamQuestion {
  return {
    id,
    number,
    type: 'extension',
    sectionTitle: '🌟 思维拓展冲顶题 (Bonus Challenge)',
    stem,
    options,
    correctAnswer: correctIndex,
    explanation,
    points: 5,
    isExtension: true,
  };
}

